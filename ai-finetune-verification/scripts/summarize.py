"""Collect every number the report uses into results/SUMMARY.md (no hand copying).

Reads results/*.json, logs/stages.jsonl, logs/*.nvidia-smi.csv and the training logs.
"""
from __future__ import annotations

import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R, L = ROOT / "results", ROOT / "logs"


def j(name):
    p = R / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def smi_peak(stage: str) -> tuple[int | None, int | None]:
    p = L / f"{stage}.nvidia-smi.csv"
    if not p.exists():
        return None, None
    vals = []
    for row in csv.reader(p.open(encoding="utf-8")):
        try:
            vals.append(int(row[1].strip().split()[0]))
        except (IndexError, ValueError):
            pass
    return (vals[0], max(vals)) if vals else (None, None)


def losses(stage: str) -> list[dict]:
    p = L / f"{stage}.log"
    if not p.exists():
        return []
    out = []
    for line in p.read_text(encoding="utf-8", errors="replace").splitlines():
        m = re.search(r"\{'loss': '([\d.]+)'.*'epoch': '([\d.]+)'", line)
        if m:
            out.append({"loss": float(m.group(1)), "epoch": float(m.group(2))})
        m = re.search(r"'eval_loss': '?([\d.]+)", line)
        if m:
            out.append({"eval_loss": float(m.group(1))})
    return out


def main() -> None:
    md = ["# Numbers used in REPORT.md (generated by scripts/summarize.py)", ""]

    md += ["## Stages (wall time, nvidia-smi whole-card MiB: first sample / peak)", "",
           "| stage | exit | seconds | first MiB | peak MiB |", "|---|---|---|---|---|"]
    if (L / "stages.jsonl").exists():
        for line in (L / "stages.jsonl").read_text(encoding="utf-8").splitlines():
            s = json.loads(line)
            md.append(f"| {s['stage']} | {s['exit']} | {s['elapsed_s']} | "
                      f"{s['nvidia_smi_first_mib']} | {s['nvidia_smi_peak_mib']} |")

    for f in ("failed/train_main_attempt1_SLEEP_OOM", "failed/train_main_attempt2_OOM_at_edge"):
        first, peak = smi_peak(f)
        md.append(f"| {f} | crashed | | {first} | {peak} |")

    for run in ("main", "template_defaults"):
        ls = [x for x in losses(f"train_{run}") if "loss" in x]
        ev = [x["eval_loss"] for x in losses(f"train_{run}") if "eval_loss" in x]
        if ls:
            md += ["", f"## Training loss: {run}", "",
                   f"first logged {ls[0]['loss']} (epoch {ls[0]['epoch']}), last {ls[-1]['loss']} "
                   f"(epoch {ls[-1]['epoch']}), min {min(x['loss'] for x in ls)}, "
                   f"logged points {len(ls)}; eval_loss: {ev}"]

    for name in ("verify_main", "verify_control_zero_B", "verify_control_tiny", "verify_template_defaults"):
        v = j(f"{name}.json")
        if not v:
            continue
        b, w = v["behaviour"], v["weights"]
        md += ["", f"## {name}: verdict **{v['verdict']}**", "",
               "| check | result |", "|---|---|"]
        md += [f"| {k} | {'PASS' if ok else 'FAIL'} |" for k, ok in v["checks"].items()]
        md += ["", f"- answer NLL base / merged / q4: " + " / ".join(
                   f"{b['nll_mean'][k]:.4f}" for k in ("base", "merged", "q4")),
               f"- base-merged {b['base_minus_merged']['mean']:.4f} "
               f"CI95 [{b['base_minus_merged']['ci95'][0]:.4f}, {b['base_minus_merged']['ci95'][1]:.4f}]",
               f"- base-q4 {b['base_minus_q4']['mean']:.4f} "
               f"CI95 [{b['base_minus_q4']['ci95'][0]:.4f}, {b['base_minus_q4']['ci95'][1]:.4f}]",
               f"- q4-merged {b['q4_minus_merged']['mean']:.4f} "
               f"CI95 [{b['q4_minus_merged']['ci95'][0]:.4f}, {b['q4_minus_merged']['ci95'][1]:.4f}]",
               f"- share of gain kept by q4: {b['share_of_gain_kept_by_q4']:.3f}",
               f"- examples better than base: merged {b['examples_better_than_base']['merged']:.3f}, "
               f"q4 {b['examples_better_than_base']['q4']:.3f}",
               f"- KL(merged||base) {b['kl_merged_vs_base']:.5f}, KL(q4||merged) {b['kl_q4_vs_merged']:.5f}",
               f"- peak allocated MiB: {b['peak_alloc_mib']}",
               f"- weights: modules {w['lora_modules']}, zero-B {w['zero_B_modules']}, scale {w['scale']}, "
               f"delta/|W| median {w['delta_rel_norm_median']:.2e}, merge err-floor max "
               f"{w['merge_err_minus_floor_max']:.4f}, bf16 floor median {w['bf16_floor_median']:.4f}, "
               f"delta visible after merge median {w['delta_visible_after_merge_median']:.3f}, "
               f"untouched tensors changed {w['non_targeted_tensors_changed']}/{w['non_targeted_tensors_checked']}",
               f"- generation: {json.dumps({k: v['generation'][k] for k in ('stopped_with_eos', 'empty', 'q4_equals_merged', 'merged_equals_base', 'mean_tokens')})}"]

    s = j("silent_checks.json")
    if s:
        md += ["", "## Silent-failure experiments (held-out answer NLL unless noted)", "",
               "| variant | NLL | non-finite | peak MiB |", "|---|---|---|---|"]
        for k, v in s.items():
            if isinstance(v, dict) and "mean_nll" in v:
                md.append(f"| {k} | {v['mean_nll']:.4f} | {v['nonfinite_examples']} | {v['peak_alloc_mib']:.0f} |")
        md.append(f"\nS4 tokenizer: {s.get('S4 tokenizer')}")

    m = j("measure_step.json")
    if m:
        md += ["", "## measure_step.py (torch allocator, worst case 1x512 tokens)", "", "| phase | allocated | max allocated | reserved | max reserved |", "|---|---|---|---|---|"]
        md += [f"| {k} | {v['allocated_mib']} | {v['max_allocated_mib']} | {v['reserved_mib']} | {v['max_reserved_mib']} |"
               for k, v in m.items()]

    for f in ("memory_budget_main_b1.json", "memory_budget_main.json"):
        b = j(f)
        if b:
            md += ["", f"## {f} (estimate before training, seq {b['seq']} batch {b['batch']})", ""]
            md += [f"- {k}: {v / 2**20:.0f} MiB" for k, v in b["bytes"].items()]

    for f in sorted(R.glob("ship_*.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        md += ["", f"## {f.name}", "", "```json", json.dumps(d, indent=1)[:2500], "```"]

    (R / "SUMMARY.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
